            <button class="faq-horo-btn">How does the Co-Axial escapement differ from the traditional Swiss Lever? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-horo-content">
              The Swiss Lever escapement operates through sliding friction: the escape wheel teeth slide across synthetic ruby pallet stones during impulse, generating friction that degrades synthetic lubricants over time. In contrast, George Daniels' Co-Axial escapement utilizes radial tangential impulses with three pallet stones, pushing the balance roller directly with near-zero sliding friction. This dramatically reduces lubrication wear, extending mechanical service intervals from 3-5 years to 8-10 years.
            </div>
          </div>
          <div class="faq-horo-item">
            <button class="faq-horo-btn">Why are sharp inward angles (angles rentrants) impossible for CNC machines to finish? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-horo-content">
              A rotary CNC milling cutter or automated diamond wheel has a circular radius; it can never cut a zero-radius, razor-sharp inward angle where two bridge chamfers intersect. Creating a sharp inward angle (angle rentrant) requires an artisan to use hand needle files and wooden pegwood sticks with diamond paste to carve a perfect knife-edge intersection by hand, representing the ultimate test of artisanal mastery for the Poin&ccedil;on de Gen&egrave;ve.
            </div>
          </div>
          <div class="faq-horo-item">
            <button class="faq-horo-btn">What is the technical difference between COSC and METAS Master Chronometer certifications? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-horo-content">
              COSC (Contr&ocirc;le Officiel Suisse des Chronom&egrave;tres) tests uncased bare movements over 15 days in 5 positions at 3 temperatures, certifying an average daily rate of -4 to +6 seconds per day with zero magnetic testing. METAS (Swiss Federal Institute of Metrology) tests fully cased finished watches across 6 positions, certifying a stricter rate of 0 to +5 seconds per day while subjecting the watch to extreme magnetic fields of 15,000 Gauss.
            </div>
          </div>
