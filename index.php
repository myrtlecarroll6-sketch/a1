            <button class="faq-horo-btn">What role does German silver (Maillechort) play in haute horlogerie movements? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-horo-content">
              German silver (Maillechort) is an alloy of copper, nickel, and zinc containing zero actual silver. It is harder and more dimensionally stable than standard brass. Crucially, Maillechort is left untreated without rhodium plating; over decades, the copper content oxidizes gently with ambient air, developing a warm, golden-honey patina prized by high-end collectors.
